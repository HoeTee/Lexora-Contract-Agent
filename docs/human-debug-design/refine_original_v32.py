def revise(source: Path, destination: Path) -> None:
    """Read the fingerprinted source; save prose edits to a distinct destination."""
    if source.resolve() == destination.resolve():
        raise ValueError("The source must not be overwritten")
    if destination.exists():
        raise FileExistsError(destination)
    source_bytes = source.read_bytes()
    if hashlib.sha256(source_bytes).hexdigest() != SOURCE_SHA256:
        raise ValueError("Source changed; re-inspect before editing")
    document = Document(source)
    if len(document.paragraphs) != 305 or len(document.tables) != 74:
        raise ValueError("Unexpected v3.2 structure")
    original_table_xml = [table._tbl.xml for table in document.tables]
    original_paragraph_xml = [paragraph._p.xml for paragraph in document.paragraphs]
    revisions = REVISIONS | APPENDIX_REVISIONS
    for index, new_text in revisions.items():
        paragraph = document.paragraphs[index]
        if len(paragraph.runs) != 1:
            raise ValueError(f"Unexpected mixed formatting at paragraph {index}")
        paragraph.runs[0].text = new_text
    for index, paragraph in enumerate(document.paragraphs):
        if index not in revisions:
            assert paragraph._p.xml == original_paragraph_xml[index]
    assert [table._tbl.xml for table in document.tables] == original_table_xml
    destination.parent.mkdir(parents=True, exist_ok=True)
    document.save(destination)
    verified = Document(destination)
    assert len(verified.inline_shapes) == len(document.inline_shapes) == 24
    assert len(verified.paragraphs) == 305
    assert [table._tbl.xml for table in verified.tables] == original_table_xml
    field_tables = [table for table in verified.tables if table.cell(0, 0).text == "全部字段"]
    assert len(field_tables) == 51
    assert sum(len(table.rows) - 1 for table in field_tables) == 334
    with ZipFile(source) as original_zip, ZipFile(destination) as revised_zip:
        for name in original_zip.namelist():
            if name.startswith("word/media/"):
                assert original_zip.read(name) == revised_zip.read(name)
    assert hashlib.sha256(source.read_bytes()).hexdigest() == SOURCE_SHA256
    print(f"Edited {len(revisions)} prose paragraphs; preserved 24 images, 74 tables, 51 structures and 334 fields")
    print(destination.resolve())


